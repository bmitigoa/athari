#!/usr/bin/env bash
#
# Athari installer. Builds the image, starts MariaDB and the web app, installs
# Drupal from the exported configuration, creates the accounts and loads the
# Kenya demo data.
#
# On a server it is started by deploy/bootstrap.sh. It can be run again safely:
# existing passwords are kept and an installed site is not reinstalled.
#
# Optional environment variables (all asked for interactively if missing):
#   ATHARI_DOMAIN          public host name; blank = <ip>.sslip.io
#   ATHARI_ACME_EMAIL      e-mail for the HTTPS certificate notices
#   ATHARI_ADMIN_MAIL      e-mail of the site administrator account
#   ATHARI_DARAJA_KEY, ATHARI_DARAJA_SECRET, ATHARI_DARAJA_PASSKEY
#   ATHARI_NONINTERACTIVE  1 = never ask, use the variables only
#   ATHARI_LOCAL_TEST      1 = local trial: host localhost, ports 8080/8443, no cron
#   ATHARI_SECRETS_DIR     default /opt/athari/secrets
#
set -euo pipefail

APP_DIR="${ATHARI_APP_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
SECRETS_DIR="${ATHARI_SECRETS_DIR:-/opt/athari/secrets}"
LOCAL_TEST="${ATHARI_LOCAL_TEST:-0}"
NONINTERACTIVE="${ATHARI_NONINTERACTIVE:-0}"

say()  { printf '\n\033[1;32m==> %s\033[0m\n' "$*"; }
note() { printf '    %s\n' "$*"; }
die()  { printf '\n\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

command -v docker >/dev/null || die "Docker is not installed. Run deploy/bootstrap.sh first."

gen_pw()  { LC_ALL=C tr -dc 'A-HJ-NP-Za-km-z2-9' </dev/urandom | head -c "${1:-24}"; }
gen_hex() { LC_ALL=C tr -dc 'a-f0-9' </dev/urandom | head -c "${1:-64}"; }

ask() { # ask VAR "Prompt" [default]
  local var="$1" prompt="$2" default="${3:-}" value="${!1:-}"
  if [ -n "$value" ] || [ "$NONINTERACTIVE" = "1" ]; then
    printf -v "$var" '%s' "${value:-$default}"
    return
  fi
  read -r -p "$prompt${default:+ [$default]}: " value
  printf -v "$var" '%s' "${value:-$default}"
}
ask_secret() { # ask_secret VAR "Prompt"  (typed text is not shown)
  local var="$1" prompt="$2" value="${!1:-}"
  if [ -n "$value" ] || [ "$NONINTERACTIVE" = "1" ]; then
    printf -v "$var" '%s' "$value"
    return
  fi
  read -r -s -p "$prompt (press Enter to skip): " value
  echo
  printf -v "$var" '%s' "$value"
}

# ------------------------------------------------------------------ settings
say "Collecting settings"
if [ "$LOCAL_TEST" = "1" ]; then
  ATHARI_DOMAIN="localhost"
  HTTP_PORT=8080
  HTTPS_PORT=8443
else
  HTTP_PORT=80
  HTTPS_PORT=443
  if [ -z "${ATHARI_DOMAIN:-}" ]; then
    ask ATHARI_DOMAIN "Public host name, for example athari.example.co.ke (blank = use a free sslip.io name from this server's IP)" ""
  fi
  if [ -z "$ATHARI_DOMAIN" ]; then
    ip="$(curl -4 -fsS https://api.ipify.org || true)"
    [ -n "$ip" ] || die "Could not detect this server's public IP. Set ATHARI_DOMAIN."
    ATHARI_DOMAIN="athari.${ip//./-}.sslip.io"
    note "Using $ATHARI_DOMAIN"
  fi
fi
ask ATHARI_ACME_EMAIL "E-mail for HTTPS certificate notices (optional)" ""
ask ATHARI_ADMIN_MAIL "E-mail for the site administrator account" "admin@${ATHARI_DOMAIN}"
ask_secret ATHARI_DARAJA_KEY "Daraja consumer key"
if [ -n "${ATHARI_DARAJA_KEY:-}" ]; then
  ask_secret ATHARI_DARAJA_SECRET "Daraja consumer secret"
  ask_secret ATHARI_DARAJA_PASSKEY "Daraja Lipa na M-Pesa passkey"
fi

# ------------------------------------------------------------ secrets on disk
say "Preparing the secrets directory ($SECRETS_DIR)"
umask 077
mkdir -p "$SECRETS_DIR"
chmod 700 "$SECRETS_DIR"
CRED="$SECRETS_DIR/credentials.env"
touch "$CRED"
chmod 600 "$CRED"
# shellcheck disable=SC1090
. "$CRED"
save() { # save NAME VALUE: keep an existing value, otherwise store the new one
  local name="$1" value="$2"
  if [ -z "${!name:-}" ]; then
    printf -v "$name" '%s' "$value"
    printf '%s=%q\n' "$name" "$value" >>"$CRED"
  fi
}
save DB_PASSWORD "$(gen_pw 28)"
save DB_ROOT_PASSWORD "$(gen_pw 28)"
save HASH_SALT "$(gen_hex 64)"
save ADMIN_USER "athari_admin"
save ADMIN_PASSWORD "$(gen_pw 24)"
save PW_NGOADMIN "$(gen_pw 24)"
save PW_FIELDOFFICER "$(gen_pw 16)"
save PW_REVIEWER "$(gen_pw 16)"

escaped_domain="${ATHARI_DOMAIN//./\\.}"
TRUSTED_HOSTS="^${escaped_domain}\$"

cat >"$SECRETS_DIR/compose.env" <<EOF
SECRETS_DIR=$SECRETS_DIR
SITE_ADDRESS=$ATHARI_DOMAIN
CADDY_GLOBAL_OPTIONS=${ATHARI_ACME_EMAIL:+email $ATHARI_ACME_EMAIL}
TRUSTED_HOSTS=$TRUSTED_HOSTS
HTTP_PORT=$HTTP_PORT
HTTPS_PORT=$HTTPS_PORT
DB_PASSWORD=$DB_PASSWORD
DB_ROOT_PASSWORD=$DB_ROOT_PASSWORD
EOF
chmod 600 "$SECRETS_DIR/compose.env"

php_quote() { printf "%s" "$1" | sed -e "s/\\\\/\\\\\\\\/g" -e "s/'/\\\\'/g"; }
public_url="https://${ATHARI_DOMAIN}"
[ "$LOCAL_TEST" = "1" ] && public_url="https://localhost:${HTTPS_PORT}"
{
  echo "<?php"
  echo "// Generated by deploy/install.sh. Machine-specific and secret: never commit."
  echo "\$databases['default']['default'] = ["
  echo "  'database' => 'athari', 'username' => 'athari', 'password' => '$(php_quote "$DB_PASSWORD")',"
  echo "  'host' => 'db', 'port' => '3306', 'driver' => 'mysql', 'prefix' => '',"
  echo "  'collation' => 'utf8mb4_general_ci',"
  echo "];"
  echo "\$settings['hash_salt'] = '$HASH_SALT';"
  echo "\$settings['trusted_host_patterns'] = ['^${escaped_domain}\$'];"
  echo "\$config['athari_donate.settings']['environment'] = 'sandbox';"
  echo "\$config['athari_donate.settings']['shortcode'] = '174379';"
  echo "\$config['athari_donate.settings']['callback_base_url'] = '$public_url';"
  if [ -n "${ATHARI_DARAJA_KEY:-}" ]; then
    echo "\$config['athari_donate.settings']['consumer_key'] = '$(php_quote "$ATHARI_DARAJA_KEY")';"
    echo "\$config['athari_donate.settings']['consumer_secret'] = '$(php_quote "${ATHARI_DARAJA_SECRET:-}")';"
    echo "\$config['athari_donate.settings']['passkey'] = '$(php_quote "${ATHARI_DARAJA_PASSKEY:-}")';"
  fi
  echo "\$config['system.site']['mail'] = '$(php_quote "$ATHARI_ADMIN_MAIL")';"
} >"$SECRETS_DIR/settings.local.php"
chmod 644 "$SECRETS_DIR/settings.local.php"   # read by the unprivileged web user inside the container

COMPOSE=(docker compose --env-file "$SECRETS_DIR/compose.env" -f "$APP_DIR/deploy/docker-compose.yml")
drush() {
  "${COMPOSE[@]}" exec -T -w /app \
    -e ATHARI_PW_FIELDOFFICER="$PW_FIELDOFFICER" -e ATHARI_PW_REVIEWER="$PW_REVIEWER" \
    -e ATHARI_PW_NGOADMIN="$PW_NGOADMIN" -e ATHARI_PW_ADMIN="$ADMIN_PASSWORD" \
    -e ATHARI_ADMIN_USER="$ADMIN_USER" -e ATHARI_ADMIN_MAIL="$ATHARI_ADMIN_MAIL" \
    app drush --root=/app/web "$@"
}

# ------------------------------------------------------------------ build + run
say "Building the image (first time: about 5 minutes)"
"${COMPOSE[@]}" build app

say "Starting the database"
"${COMPOSE[@]}" up -d --wait db

say "Starting the web app"
"${COMPOSE[@]}" up -d app
for i in $(seq 1 30); do
  if "${COMPOSE[@]}" exec -T app php -v >/dev/null 2>&1; then break; fi
  sleep 2
done

# ---------------------------------------------------------------- install Drupal
if drush status --field=bootstrap 2>/dev/null | grep -q Successful; then
  say "Drupal is already installed: leaving the database as it is"
else
  say "Installing Drupal from the exported configuration"
  drush site:install --existing-config --yes \
    --account-name="$ADMIN_USER" --account-pass="$(gen_pw 32)" --account-mail="$ATHARI_ADMIN_MAIL" \
    --site-name=Athari
fi

say "Creating accounts and the administrator password"
drush php:script deploy/create-users.php

say "Loading the Kenya demo data"
drush php:script deploy/create-sectors.php
drush php:script scripts/kenya-01-regions.php
drush php:script scripts/kenya-03-seed.php
drush php:script scripts/day3-06-menu-about.php
drush cache:rebuild

# ----------------------------------------------------------------------- cron
if [ "$LOCAL_TEST" != "1" ] && [ "$(id -u)" = "0" ]; then
  say "Scheduling cron and nightly backups"
  cat >/etc/cron.d/athari <<EOF
# Drupal cron (donation time-outs, cache cleanup) every 15 minutes.
*/15 * * * * root cd $APP_DIR/deploy && ATHARI_SECRETS_DIR=$SECRETS_DIR ./cron.sh >/dev/null 2>&1
# Database and files backup, daily at 02:30.
30 2 * * * root cd $APP_DIR/deploy && ATHARI_SECRETS_DIR=$SECRETS_DIR ./backup.sh >>/var/log/athari-backup.log 2>&1
EOF
  chmod 644 /etc/cron.d/athari
fi

# ------------------------------------------------------------------ health check
say "Checking the site"
check_url="https://${ATHARI_DOMAIN}/"
curl_opts=(-fsS -o /dev/null -w '%{http_code}')
if [ "$LOCAL_TEST" = "1" ]; then
  check_url="https://localhost:${HTTPS_PORT}/"
  curl_opts+=(-k)
fi
code=000
for i in $(seq 1 45); do
  code="$(curl "${curl_opts[@]}" "$check_url" 2>/dev/null || true)"
  [ "$code" = "200" ] && break
  sleep 4
done
[ "$code" = "200" ] || die "The site did not answer 200 at $check_url (last status: $code). Run: docker compose --env-file $SECRETS_DIR/compose.env -f $APP_DIR/deploy/docker-compose.yml logs app"

cat <<EOF

============================================================================
  Athari is running:  $public_url

  Demo logins (limited staff accounts, safe to share):
      fieldofficer   $PW_FIELDOFFICER
      reviewer       $PW_REVIEWER

  The administrator login and every other secret are stored on this
  server only, and are NOT shown here:
      $CRED   (readable by root only)
  Administrator user name: $ADMIN_USER
============================================================================
EOF
